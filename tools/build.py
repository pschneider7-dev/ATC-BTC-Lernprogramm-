"""Generates the data files of the app from the content specs in tools/content/.

    python3 tools/build.py

Every doctrinal text in the app is produced here from the source publications (tools/src/), so it is
the original wording with source and page. The specs only add headings, questions and the
cross-check tasks for the print publications.
"""
import importlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, 'content'))

import lib  # noqa: E402

HEADER = '/* Generated by tools/build.py from the source publications – do not edit by hand. */\n'


def js(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(HEADER + text)
    print('wrote', rel)


def build_list(modname, var, render_item):
    try:
        mod = importlib.import_module(modname)
    except ModuleNotFoundError:
        return
    items = [render_item(x) for x in mod.ITEMS]
    write('data/%s.js' % modname, '(function () {\n  var L = window.LP.%s;\n  ' % var +
          js(items).replace('\n', '\n  ') + '.forEach(function (x) { L.push(x); });\n})();\n')


if __name__ == '__main__':
    # Die Modul-Spezifikationen (content/m01–m14) liefern nur noch Bausteine für Spickzettel und Reihenfolgen;
    # Module, Karteikarten und Quiz entstehen in der App aus der privaten Inhaltsdatei.
    for extra in ('glossary', 'brevity', 'scripts', 'spick', 'sequences', 'kontrolle', 'calcrefs'):
        try:
            mod = importlib.import_module(extra)
        except ModuleNotFoundError:
            continue
        text = mod.build()
        write('data/%s.js' % extra, text)
    import pwa
    pwa.write()
