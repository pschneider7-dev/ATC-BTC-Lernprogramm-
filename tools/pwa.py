"""Writes sw.js, the service worker that stores the whole app on the device (offline use, installable app).

    python3 tools/pwa.py

The file list and a hash over all file contents go into sw.js, so every change to the app produces a new
service worker; the phone then loads the new version in the background and uses it from the next start.
tools/build.py runs this at the end, and the GitHub Pages workflow runs it again before publishing."""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOP = ['index.html', 'manifest.webmanifest']
DIRS = ['assets', 'data']
SKIP_EXT = {'.md', '.txt'}

TEMPLATE = """/* Generated by tools/pwa.py – do not edit by hand.
   Speichert die ganze App auf dem Gerät (offline) und holt neue Versionen im Hintergrund. */
'use strict';
const VERSION = '%(version)s';
const CACHE = 'jtac-' + VERSION;
const FILES = %(files)s;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('jtac-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Startseite immer aus dem Gerätespeicher: die App öffnet auch ohne Netz
    event.respondWith(caches.match('index.html').then((res) => res || fetch(req)));
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((res) => res || fetch(req)));
});
"""


def files():
    out = list(TOP)
    for d in DIRS:
        for base, _, names in os.walk(os.path.join(ROOT, d)):
            for n in sorted(names):
                if os.path.splitext(n)[1] in SKIP_EXT or n.startswith('.'):
                    continue
                out.append(os.path.relpath(os.path.join(base, n), ROOT).replace(os.sep, '/'))
    return sorted(set(out), key=lambda p: (p.count('/'), p))


def write():
    names = files()
    h = hashlib.sha256()
    for n in names:
        h.update(n.encode())
        with open(os.path.join(ROOT, n), 'rb') as f:
            h.update(f.read())
    version = h.hexdigest()[:12]
    text = TEMPLATE % {'version': version, 'files': json.dumps(['./'] + names, indent=2)}
    with open(os.path.join(ROOT, 'sw.js'), 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote sw.js', version, len(names), 'files')


if __name__ == '__main__':
    write()
