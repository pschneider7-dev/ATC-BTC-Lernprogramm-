def build():
    out = []
    for t, l, m, q in ITEMS:
        e = {'t': t, 'l': l, 'm': m, 'd': '', 'src': []}
        if q is not None:
            e['d'] = esc(q.text).replace('\n\n', '\n')
            e['src'] = [q.ref]
        out.append(e)
    return push_js('glossary', out)
